#!/usr/bin/env bash
# Create a CloudFront distribution in front of mood-meter-app/dist/ (public S3 origin).
# Serves https://<id>.cloudfront.net/index.html and /icon-test.html (OriginPath=/dist).
# Uses the CloudFront default certificate (*.cloudfront.net) — no ACM/custom domain required.
#
# Requires IAM: cloudfront:CreateDistribution (+ Get/List for verify). See iam-cloudfront-policy.json.
# No secrets in this repo — credentials via env / IAM / Cursor secrets.
# pragma: allowlist secret — region is public infra metadata, not a credential
set -euo pipefail

REGION="${AWS_DEFAULT_REGION:-${AWS_REGION:-}}"
if [[ -z "$REGION" ]]; then
  echo "Set AWS_DEFAULT_REGION or AWS_REGION." >&2
  exit 1
fi

BUCKET="${MOOD_METER_S3_BUCKET:-mood-meter-app}"
ORIGIN_DOMAIN="${BUCKET}.s3.${REGION}.amazonaws.com"
CALLER_REF="${MOOD_METER_CF_CALLER_REF:-mood-meter-cf-$(date +%s)}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_ENV="${MOOD_METER_CF_ENV_FILE:-${ROOT}/scripts/cloudfront.local.env}"

# AWS-managed policies (global IDs): CachingOptimized + CORS-S3Origin
CACHE_POLICY_ID="658327ea-f89d-4fab-a63d-7e88639e58f6"
ORIGIN_REQUEST_POLICY_ID="88a5eaf4-2fd4-4709-b370-b4c650ea3fcf"

CONFIG="$(mktemp)"
trap 'rm -f "$CONFIG"' EXIT

cat >"$CONFIG" <<EOF
{
  "CallerReference": "${CALLER_REF}",
  "Comment": "Mood Meter static HTTPS — S3 ${BUCKET}/dist via OriginPath",
  "Enabled": true,
  "DefaultRootObject": "index.html",
  "Origins": {
    "Quantity": 1,
    "Items": [
      {
        "Id": "mood-meter-app-s3",
        "DomainName": "${ORIGIN_DOMAIN}",
        "OriginPath": "/dist",
        "CustomHeaders": { "Quantity": 0 },
        "S3OriginConfig": { "OriginAccessIdentity": "" },
        "ConnectionAttempts": 3,
        "ConnectionTimeout": 10,
        "OriginShield": { "Enabled": false },
        "OriginAccessControlId": ""
      }
    ]
  },
  "DefaultCacheBehavior": {
    "TargetOriginId": "mood-meter-app-s3",
    "ViewerProtocolPolicy": "redirect-to-https",
    "AllowedMethods": {
      "Quantity": 3,
      "Items": ["HEAD", "GET", "OPTIONS"],
      "CachedMethods": { "Quantity": 2, "Items": ["HEAD", "GET"] }
    },
    "Compress": true,
    "SmoothStreaming": false,
    "TrustedSigners": { "Enabled": false, "Quantity": 0 },
    "TrustedKeyGroups": { "Enabled": false, "Quantity": 0 },
    "LambdaFunctionAssociations": { "Quantity": 0 },
    "FunctionAssociations": { "Quantity": 0 },
    "FieldLevelEncryptionId": "",
    "CachePolicyId": "${CACHE_POLICY_ID}",
    "OriginRequestPolicyId": "${ORIGIN_REQUEST_POLICY_ID}",
    "GrpcConfig": { "Enabled": false }
  },
  "CacheBehaviors": { "Quantity": 0 },
  "CustomErrorResponses": { "Quantity": 0 },
  "PriceClass": "PriceClass_100",
  "Aliases": { "Quantity": 0 },
  "Logging": { "Enabled": false, "IncludeCookies": false, "Bucket": "", "Prefix": "" },
  "WebACLId": "",
  "HttpVersion": "http2and3",
  "IsIPV6Enabled": true,
  "Restrictions": {
    "GeoRestriction": { "RestrictionType": "none", "Quantity": 0 }
  },
  "ViewerCertificate": {
    "CloudFrontDefaultCertificate": true,
    "MinimumProtocolVersion": "TLSv1.2_2021"
  }
}
EOF

echo "Creating CloudFront distribution for s3://${BUCKET}/dist (origin ${ORIGIN_DOMAIN})..."
if ! OUT="$(aws cloudfront create-distribution --distribution-config "file://${CONFIG}" --output json 2>&1)"; then
  echo "$OUT" >&2
  if echo "$OUT" | grep -qi AccessDenied; then
    echo >&2
    echo "IAM blocked CloudFront. Attach scripts/iam-cloudfront-policy.json to user cursor-mood-meter" >&2
    echo "(or create the distribution in console with Origin=${ORIGIN_DOMAIN}, OriginPath=/dist," >&2
    echo " DefaultRootObject=index.html, default cert), then set MOOD_METER_CLOUDFRONT_DISTRIBUTION_ID" >&2
    echo "and MOOD_METER_CLOUDFRONT_DOMAIN in scripts/cloudfront.local.env." >&2
  fi
  exit 1
fi

DIST_ID="$(echo "$OUT" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Distribution"]["Id"])')"
DOMAIN="$(echo "$OUT" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Distribution"]["DomainName"])')"
STATUS="$(echo "$OUT" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Distribution"]["Status"])')"

umask 077
cat >"$OUT_ENV" <<EOF
# Generated by scripts/create-cloudfront.sh — do not commit (gitignored).
MOOD_METER_CLOUDFRONT_DISTRIBUTION_ID=${DIST_ID}
MOOD_METER_CLOUDFRONT_DOMAIN=${DOMAIN}
EOF

echo "Created distribution ${DIST_ID} (${STATUS})"
echo "  App:       https://${DOMAIN}/index.html"
echo "  Icon test: https://${DOMAIN}/icon-test.html"
echo "Wrote ${OUT_ENV}"
echo "Wait until Status=Deployed (often several minutes), then verify Content-Types and Add-to-Home."
echo "Optional: ./scripts/invalidate-cloudfront.sh"
